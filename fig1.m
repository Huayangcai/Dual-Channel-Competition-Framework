%% =========================== LOCAL FUNCTIONS ===========================

function drawOpposingChannels( ...
    ax, xCenter, yCenter, jPlus, jMinus, ...
    lengthScale, blue, orange, dark)
% Draw two opposing channel contributions from a common origin.

leftEnd  = xCenter-lengthScale*jMinus;
rightEnd = xCenter+lengthScale*jPlus;

% Channel lines
plot(ax, [xCenter, leftEnd], [yCenter, yCenter], '-', ...
    'Color', blue, ...
    'LineWidth', 4.0);

plot(ax, [xCenter, rightEnd], [yCenter, yCenter], '-', ...
    'Color', orange, ...
    'LineWidth', 4.0);

% Arrowhead dimensions in panel-(a) coordinates
headLength = 0.007;
headHeight = 0.024;

% Left arrowhead
patch(ax, ...
    [leftEnd, leftEnd+headLength, leftEnd+headLength], ...
    [yCenter, yCenter+headHeight, yCenter-headHeight], ...
    blue, ...
    'EdgeColor', blue);

% Right arrowhead
patch(ax, ...
    [rightEnd, rightEnd-headLength, rightEnd-headLength], ...
    [yCenter, yCenter+headHeight, yCenter-headHeight], ...
    orange, ...
    'EdgeColor', orange);

% Common origin
tickHeight = 0.040;

plot(ax, ...
    [xCenter, xCenter], ...
    [yCenter-tickHeight, yCenter+tickHeight], ...
    '-', ...
    'Color', dark, ...
    'LineWidth', 1.0);

end


function plotGradientLine(ax, x, y, colorVariable, cmap, lineWidth)
% Plot a curve with color determined by values between -1 and 1.

numberOfColors = size(cmap,1);

for k = 1:numel(x)-1

    colorIndex = 1+round( ...
        (numberOfColors-1)*(colorVariable(k)+1)/2);

    colorIndex = max(1,min(numberOfColors,colorIndex));

    plot(ax, ...
        x(k:k+1), ...
        y(k:k+1), ...
        '-', ...
        'Color', cmap(colorIndex,:), ...
        'LineWidth', lineWidth);

end

end


function plotStateMarker(ax, xValue, yValue, markerType, dark)
% Marker shapes provide identification independent of color.

plot(ax, xValue, yValue, ...
    'LineStyle', 'none', ...
    'Marker', markerType, ...
    'MarkerSize', 7.5, ...
    'MarkerFaceColor', 'w', ...
    'MarkerEdgeColor', dark, ...
    'LineWidth', 1.2);

end


function formatAxes(ax)
% Journal-style axes formatting.

set(ax, ...
    'FontName', 'Arial', ...
    'FontSize', 9, ...
    'LineWidth', 0.85, ...
    'TickDir', 'out', ...
    'TickLength', [0.018, 0.018], ...
    'Box', 'on', ...
    'Layer', 'top', ...
    'XColor', [0.12, 0.12, 0.12], ...
    'YColor', [0.12, 0.12, 0.12]);

grid(ax, 'off');

end


function cmap = turboR2019b(n)
% Backward-compatible Turbo colormap approximation.

if nargin < 1
    n = 256;
end

x = linspace(0,1,n)';

x2 = x.^2;
x3 = x.^3;
x4 = x.^4;
x5 = x.^5;

kRed = [ ...
     0.13572138, ...
     4.61539260, ...
   -42.66032258, ...
   132.13108234, ...
  -152.94239396, ...
    59.28637943];

kGreen = [ ...
     0.09140261, ...
     2.19418839, ...
     4.84296658, ...
   -14.18503333, ...
     4.27729857, ...
     2.82956604];

kBlue = [ ...
      0.10667330, ...
     12.64194608, ...
    -60.58204836, ...
    110.36276771, ...
    -89.90310912, ...
     27.34824973];

X = [ones(n,1), x, x2, x3, x4, x5];

redChannel   = X*kRed';
greenChannel = X*kGreen';
blueChannel  = X*kBlue';

cmap = [redChannel, greenChannel, blueChannel];

cmap(cmap < 0) = 0;
cmap(cmap > 1) = 1;

end