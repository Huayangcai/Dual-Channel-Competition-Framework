        orange, ...
        dark);

end

% Small labels below the state diagrams
text(axA, stateCenters(1), 0.205, ...
    'negative dominance', ...
    'FontName', 'Arial', ...
    'FontSize', 8.2, ...
    'Color', gray, ...
    'HorizontalAlignment', 'center');

text(axA, stateCenters(2), 0.205, ...
    'exact balance', ...
    'FontName', 'Arial', ...
    'FontSize', 8.2, ...
