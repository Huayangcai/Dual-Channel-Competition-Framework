%% Local functions

function state = scalarState(H,opt)

    alpha = acos(1-H);
    sa = sin(alpha);
    ca = cos(alpha);

    % Poisson-baseline discharge.
    QD = ...
        alpha/8 ...
        - sin(2*alpha)/12 ...
        + sin(4*alpha)/96;

    % Rigid-lid discharge.
    ID = integral( ...
        @(k) kernelID(k,alpha), ...
        0,opt.kMax, ...
        'RelTol',opt.RelTol, ...
        'AbsTol',opt.AbsTol);

    Qseg = ...
        cot(alpha)/6 ...
        + alpha/(8*sa^4) ...
        - ca*(5-2*ca^2)/(24*sa^3) ...
        - pi*ID;

    QRL = sa^4*Qseg;

    % Physical free-surface discharge.
    IN = integral( ...
        @(k) kernelIN(k,alpha), ...
        0,opt.kMax, ...
        'RelTol',opt.RelTol, ...
        'AbsTol',opt.AbsTol);

    QFS = ...
        (alpha ...
        - sin(2*alpha) ...
        + 0.25*sin(4*alpha) ...
        + 2*pi*sin(2*alpha)^2*IN)/8;

    % Boundary competition channels.
    CQ = QD-QRL;
    RQ = QFS-QRL;
    SB = RQ-CQ;

    PiB = SB^2/max(RQ,CQ);

    % Whole-transport competition channels.
    JplusQ = QD+RQ;
    PiQ = QFS^2/JplusQ;

    state.QD  = QD;
    state.QRL = QRL;
    state.QFS = QFS;
    state.CQ  = CQ;
    state.RQ  = RQ;
    state.SB  = SB;
    state.PiB = PiB;
    state.PiQ = PiQ;

end


function y = kernelID(k,alpha)

    y = zeros(size(k));
    small = abs(k)<1.0e-7;
    large = ~small;

    % Exact limit as k approaches zero.
    y(small) = 1/(alpha*pi^2);

    kk = k(large);
    y(large) = ...
        kk.^3 ./ ...
        (tanh(alpha*kk).*sinh(pi*kk).^2);

end


function y = kernelIN(k,alpha)

    y = zeros(size(k));
    small = abs(k)<1.0e-7;
    large = ~small;

    % Exact limit as k approaches zero.
    y(small) = alpha/pi^2;

    kk = k(large);
    y(large) = ...
        kk.*tanh(alpha*kk) ./ ...
        sinh(pi*kk).^2;

end


function value = metricValue(H,name,opt)

    state = scalarState(H,opt);

    switch name
        case 'QFS'
            value = state.QFS;
        case 'PiB'
            value = state.PiB;
        case 'PiQ'
            value = state.PiQ;
        otherwise
            error('Unknown metric: %s',name);
    end

end
