%% Fig. 5: Hydraulic performance diagnostics
% This script is self-contained. It evaluates the exact scalar expressions,
% locates the three characteristic filling states independently of the
% plotting grid, and draws the two-panel figure with a peak-region inset.

clear; clc; close all;

set(groot, ...
    'defaultAxesFontName','Arial', ...
    'defaultTextFontName','Arial');

%% 1. Numerical settings

Hmin = 0.01;
Hmax = 1.99;
H = linspace(Hmin,Hmax,401).';

optMain.kMax   = 12;
optMain.RelTol = 1.0e-10;
optMain.AbsTol = 1.0e-12;

optRef.kMax   = 16;
optRef.RelTol = 1.0e-12;
optRef.AbsTol = 1.0e-14;

%% 2. Evaluate the three diagnostics

nH = numel(H);
QFS = zeros(nH,1);
PiB = zeros(nH,1);
PiQ = zeros(nH,1);

for iH = 1:nH
    state = scalarState(H(iH),optMain);
    QFS(iH) = state.QFS;
    PiB(iH) = state.PiB;
    PiQ(iH) = state.PiQ;
end

Y = [QFS PiB PiQ];
metricNames = {'QFS','PiB','PiQ'};

%% 3. Locate the characteristic filling states

optSearch = optimset( ...
    'TolX',1.0e-10, ...
    'Display','off');

HQ = fminbnd( ...
    @(h) -metricValue(h,'QFS',optRef), ...
    Hmin,Hmax,optSearch);

HB = fminbnd( ...
    @(h) -metricValue(h,'PiB',optRef), ...
    Hmin,Hmax,optSearch);

HT = fminbnd( ...
    @(h) -metricValue(h,'PiQ',optRef), ...
    Hmin,Hmax,optSearch);

stateQ = scalarState(HQ,optRef);
stateB = scalarState(HB,optRef);
stateT = scalarState(HT,optRef);

Hstar = [HQ HB HT];
Ystar = [stateQ.QFS stateB.PiB stateT.PiQ];

%% 4. Normalize each diagnostic by its independently optimized maximum

Yn = bsxfun(@rdivide,Y,Ystar);

fprintf('\nCharacteristic filling states used in Fig. 5:\n');
fprintf('  H_Q^* = %.8f, Q_FS,max = %.8f\n',HQ,stateQ.QFS);
fprintf('  H_B^* = %.8f, Pi_B,max = %.8f\n',HB,stateB.PiB);
fprintf('  H_T^* = %.8f, Pi_Q,max = %.8f\n',HT,stateT.PiQ);

